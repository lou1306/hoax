"""Boolean-network (``.bnet``) parsing and direct transition semantics.

This module implements the Boolean-network backend, which does *not* go
through an HOA.  A network is an ordered list of update functions ``f_v``,
and its transition relation is available directly: from a state ``x`` a
variable ``v`` may fire whenever ``f_v(x) != x_v``, and firing it flips
``x_v``.  Any subset of those variables may fire simultaneously, so the
successors of ``x`` are the corner box generated by the variables whose
update differs from their current value.

Because the update functions are explicit, no SAT/AllSAT step is needed:
:meth:`BNet.successors` evaluates them once for the current state and
enumerates the resulting flips.  Under an independent-firing semantics the
firing of a variable is recoverable from ``(x_v, x'_v)``; for a variable
that does not change it is unobservable, so the fire and the no-fire events
lead to the same successor and their probabilities sum to one.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from functools import cached_property
from pathlib import Path
from typing import Callable, Optional

from ._bnet_parser import Lark_StandAlone, Transformer, UnexpectedInput, v_args
from .util import Model, prob

# ---------------------------------------------------------------------------
# Expressions
# ---------------------------------------------------------------------------

class Expr:
    """Base class for Boolean-network update expressions."""


@dataclass(frozen=True)
class Var(Expr):
    name: str


@dataclass(frozen=True)
class Const(Expr):
    value: bool


@dataclass(frozen=True)
class Not(Expr):
    arg: Expr


@dataclass(frozen=True)
class And(Expr):
    args: tuple[Expr, ...]


@dataclass(frozen=True)
class Or(Expr):
    args: tuple[Expr, ...]


def vars_of(e: Expr, acc: Optional[set[str]] = None) -> set[str]:
    """Return the set of variables occurring in ``e``."""
    if acc is None:
        acc = set()
    if isinstance(e, Var):
        acc.add(e.name)
    elif isinstance(e, Not):
        vars_of(e.arg, acc)
    elif isinstance(e, (And, Or)):
        for a in e.args:
            vars_of(a, acc)
    return acc


def eval_expr(e: Expr, values: dict[str, bool]) -> bool:
    """Evaluate ``e`` under a total (or partial, for variables not occurring) valuation."""
    if isinstance(e, Const):
        return e.value
    if isinstance(e, Var):
        return values[e.name]
    if isinstance(e, Not):
        return not eval_expr(e.arg, values)
    if isinstance(e, And):
        return all(eval_expr(a, values) for a in e.args)
    if isinstance(e, Or):
        return any(eval_expr(a, values) for a in e.args)
    raise TypeError(f"Unexpected expression {e!r}")


CompiledExpr = Callable[[list[bool]], bool]


def _combine_and(funcs: tuple[CompiledExpr, ...]) -> CompiledExpr:
    """Combine closures into a balanced, short-circuiting ``and`` tree."""
    if not funcs:
        return lambda values: True
    if len(funcs) == 1:
        return funcs[0]
    mid = len(funcs) // 2
    left = _combine_and(funcs[:mid])
    right = _combine_and(funcs[mid:])
    return lambda values: left(values) and right(values)


def _combine_or(funcs: tuple[CompiledExpr, ...]) -> CompiledExpr:
    """Combine closures into a balanced, short-circuiting ``or`` tree."""
    if not funcs:
        return lambda values: False
    if len(funcs) == 1:
        return funcs[0]
    mid = len(funcs) // 2
    left = _combine_or(funcs[:mid])
    right = _combine_or(funcs[mid:])
    return lambda values: left(values) or right(values)


def compile_expr(e: Expr, index: dict[str, int]) -> CompiledExpr:
    """Compile an expression into a closure over a list of Boolean values.

    This removes recursive ``isinstance`` dispatch and dictionary lookups from
    the evaluation hot path without generating or executing source code.
    """
    if isinstance(e, Var):
        i = index[e.name]
        return lambda values: values[i]
    if isinstance(e, Const):
        value = e.value
        return lambda values: value
    if isinstance(e, Not):
        arg = compile_expr(e.arg, index)
        return lambda values: not arg(values)
    if isinstance(e, And):
        return _combine_and(tuple(compile_expr(a, index) for a in e.args))
    if isinstance(e, Or):
        return _combine_or(tuple(compile_expr(a, index) for a in e.args))
    raise TypeError(f"Unexpected expression {e!r}")


