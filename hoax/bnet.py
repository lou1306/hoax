# Generated with:
#   python -m lark.tools.standalone -s start -s expr hoax/bnet.lark \
#       -o hoax/_bnet_parser.py
# The standalone parser embeds the LALR tables, so importing hoax.bnet no
# longer builds the grammar tables at startup.
_PARSER = Lark_StandAlone()


@v_args(inline=True)
class _ToAST(Transformer):
    """Turn a Lark parse tree into :class:`Expr` objects and rule pairs."""

    # -- expressions --------------------------------------------------------

    def or_(self, a: Expr, b: Expr) -> Expr:
        return Or(a.args + (b,)) if isinstance(a, Or) else Or((a, b))

    def and_(self, a: Expr, b: Expr) -> Expr:
        return And(a.args + (b,)) if isinstance(a, And) else And((a, b))

    def not_(self, arg: Expr) -> Expr:
        return Not(arg)

    def const_(self, tok) -> Expr:
        return Const(str(tok) == "1")

    def var_(self, tok) -> Expr:
        return Var(str(tok))

    # -- rules --------------------------------------------------------------

    def rule_fn(self, name, expr: Expr) -> tuple[str, Optional[Expr]]:
        return str(name), expr

    def rule_empty(self, name) -> tuple[str, Optional[Expr]]:
        return str(name), None

    def bare(self, name) -> tuple[str, Optional[Expr]]:
        return str(name), None

    def start(self, *rules: tuple[str, Optional[Expr]]) -> list[tuple[str, Optional[Expr]]]:
        return list(rules)


_TO_AST = _ToAST()


def tokenize(text: str) -> list[str]:
    """Split a Boolean expression into names and operators.

    This is a thin wrapper over the Lark lexer, kept for backwards
    compatibility; the parser itself is entirely grammar-driven.
    """
    return [tok.value for tok in _PARSER.lex(text) if tok.type != "_NEWLINE"]


def parse_expr(text: str) -> Expr:
    """Parse a Boolean expression such as ``!a&b | c``."""
    text = text.strip()
    if not text:
        raise ValueError("empty expression")
    try:
        return _TO_AST.transform(_PARSER.parse(text, start="expr"))
    except UnexpectedInput as e:
        raise ValueError(f"invalid expression {text!r}: {e}") from e


@dataclass
class BNet:
    """A Boolean network: an ordered list of variables and their update functions."""

    names: list[str]
    index: dict[str, int]
    update: list[Expr]

    @property
    def n(self) -> int:
        return len(self.names)

    def value_at(self, state: int, name: str) -> bool:
        return bool((state >> self.index[name]) & 1)

    def state_from_values(self, values: dict[str, bool]) -> int:
        state = 0
        for name, bit in values.items():
            if bit:
                state |= 1 << self.index[name]
        return state

    def state_values(self, state: int) -> dict[str, bool]:
        return {name: bool((state >> i) & 1) for i, name in enumerate(self.names)}

    @cached_property
    def _compiled_update(self) -> tuple[CompiledExpr, ...]:
        """Closures for the update functions, built lazily once per network."""
        return tuple(compile_expr(e, self.index) for e in self.update)

    def potential_changes(self, state: int) -> list[int]:
        """Indices of the variables whose update differs from their current value.

        Those are exactly the variables that may fire: a variable that does
        not change cannot fire, and firing it would change it.
        """
        values = [bool((state >> i) & 1) for i in range(self.n)]
        return [
            i for i, f in enumerate(self._compiled_update)
            if f(values) != values[i]
        ]

    def models(self, state: int) -> list[tuple[Model, str, int]]:
        """Return ``(firing_model, string, next_state)`` for every successor of ``state``.

        Firing an independent subset of the variables that may change flips
        exactly that subset, so the successors are the ``2**k`` corner box of
        :meth:`potential_changes`.  The firing model mentions exactly those
        variables, with value ``True`` when the variable changes; it
        determines the next state and vice versa.
        """
        changes = self.potential_changes(state)
        entries: list[tuple[Model, str, int]] = []
        for mask in range(1 << len(changes)):
            nxt = state
            model: list[tuple[str, bool]] = []
            for bit, i in enumerate(changes):
                fired = bool((mask >> bit) & 1)
                if fired:
                    nxt ^= 1 << i
                model.append((self.names[i], fired))
            m_str = "{" + ";".join(("" if fired else "!") + name for name, fired in model) + "}"
            entries.append((tuple(model), m_str, nxt))
        entries.sort(key=lambda e: e[2])
        return entries

    def successors(self, state: int) -> list[int]:
        """Successor states, i.e. the flips of every subset of the changeable variables."""
        return [nxt for _, _, nxt in self.models(state)]

    def trel(self, state: int, pr: dict[str, float],
             stutter: bool = True) -> list[tuple[float, tuple[Model, str, int]]]:
        """Build the cumulative transition distribution out of ``state``.

        Every successor is reached by firing an independent subset of the
        variables that may change, hence its probability is
        ``PROD_v (p_v if v changes else 1 - p_v)`` over those variables.
        Variables that do not change are unobservable and contribute one.

        With ``stutter=False`` the no-change leaf is removed and the rest
        renormalised, which is the PrGA stutter-free conditioning.  A
        steady state (or a state where no variable fires with positive
        probability) then has no outgoing transition and the empty list is
        returned.
        """
        entries = self.models(state)
        if not stutter:
            entries = [entry for entry in entries if entry[2] != state]
            if not entries:
                return []
        total = 0.0
        result: list[tuple[float, tuple[Model, str, int]]] = []
        for model, m_str, nxt in entries:
            total += prob(model, pr)
            result.append((total, (model, m_str, nxt)))
        if not stutter:
            if total <= 0.0:
                return []
            result = [(cumulative / total, entry)
                      for cumulative, entry in result]
        else:
            assert abs(total - 1.0) < 1e-6, (
                f"cumulative probability {total} for state {state}")
        result[-1] = (1.0, result[-1][1])
        return result

    def sample(self, state: int, pr: dict[str, float], r: float,
               changes: Optional[list[int]] = None,
               stutter: bool = True) -> tuple[Model, str, int]:
        """Pick a single successor with an explicit uniform draw ``r``.

        This is the on-the-fly counterpart of :func:`hoax.util.pick` over
        :meth:`trel`: it returns the very same leaf a cumulative scan would,
        but in ``O(k)`` time and ``O(1)`` memory instead of materialising the
        ``2**k`` successors (``k`` = number of variables that may change).

        The leaves are ordered by increasing next state, so the highest-index
        changeable variable decides the outermost split and each node puts the
        branch whose next value is 0 first.  The probability of that branch is
        ``1 - p_v`` if ``v`` currently holds 0 and ``p_v`` if it holds 1, which
        is the only split probability needed (the other variables' factors
        cancel).

        ``changes`` may be passed in to reuse a cached
        :meth:`potential_changes`.

        With ``stutter=False`` the draw is conditioned on at least one
        variable firing; :meth:`sample_stutter_free` implements that case.
        """
        if not stutter:
            return self.sample_stutter_free(state, pr, r, changes)
        if changes is None:
            changes = self.potential_changes(state)
        lo, hi = 0.0, 1.0
        fired = [False] * len(changes)
        for bit in range(len(changes) - 1, -1, -1):
            v = changes[bit]
            value = (state >> v) & 1
            p = pr[self.names[v]]
            # Probability that the next value of v is 0.
            q = (1.0 - p) if value == 0 else p
            mid = lo + (hi - lo) * q
            if r < mid:
                hi = mid
                fired[bit] = value == 1
            else:
                lo = mid
                fired[bit] = value == 0
        return self._assemble(state, changes, fired)

    def sample_stutter_free(self, state: int, pr: dict[str, float], r: float,
                            changes: Optional[list[int]] = None
                            ) -> tuple[Model, str, int]:
        """Pick a successor conditioned on at least one variable firing.

        This is the same lexicographic inverse-CDF descent as :meth:`sample`
        over the PrGA weights, restricted to the non-empty firing subsets
        and renormalised.  While no variable has fired yet, the branch
        probabilities are conditioned on the variables below the current
        one containing at least one fire.  The probability of *no* fire is
        accumulated in log space so that the conditioning stays accurate
        when the firing probabilities are small.

        Raises ``ValueError`` if no variable can fire, since the
        conditioning event then has probability zero.
        """
        if changes is None:
            changes = self.potential_changes(state)
        if not changes:
            raise ValueError("stutter-free sampling is undefined at a steady state")
        if all(pr[self.names[v]] <= 0.0 for v in changes):
            raise ValueError(
                "stutter-free sampling needs a positive firing probability")

        # log P(no fire among changes[:j]) for j = 0 .. k.
        log_none = [0.0] * (len(changes) + 1)
        for bit, v in enumerate(changes):
            p = pr[self.names[v]]
            log_none[bit + 1] = (
                -math.inf if p >= 1.0 else log_none[bit] + math.log1p(-p))

        lo, hi = 0.0, 1.0
        fired = [False] * len(changes)
        fired_any = False
        for bit in range(len(changes) - 1, -1, -1):
            v = changes[bit]
            value = (state >> v) & 1
            p = pr[self.names[v]]
            if fired_any:
                # The conditioning is already satisfied: plain PrGA split.
                q = (1.0 - p) if value == 0 else p
            else:
                # Probability that the variables below this one contain at
                # least one fire, given that none has fired so far.
                rest = -math.expm1(log_none[bit])
                if value == 0:
                    q = (1.0 - p) * rest / ((1.0 - p) * rest + p)
                else:
                    q = p / (p + (1.0 - p) * rest)
            q = min(1.0, max(0.0, q))
            mid = lo + (hi - lo) * q
            if r < mid:
                hi = mid
                fired[bit] = value == 1
            else:
                lo = mid
                fired[bit] = value == 0
            fired_any = fired_any or fired[bit]
        return self._assemble(state, changes, fired)

    def sample_async(self, state: int, r: float,
                     changes: Optional[list[int]] = None
                     ) -> tuple[Model, str, int]:
        """Pick one uniformly chosen changeable variable and flip it.

        This is the exact uniform-asynchronous update: no stuttering and no
        multi-variable flips.  ``r`` is a uniform draw in ``[0, 1)``; a single
        changeable variable is deterministic and does not need a draw.
        """
        if changes is None:
            changes = self.potential_changes(state)
        if not changes:
            raise ValueError("uniform async sampling is undefined at a steady state")
        idx = min(max(int(r * len(changes)), 0), len(changes) - 1)
        fired = [False] * len(changes)
        fired[idx] = True
        return self._assemble(state, changes, fired)

    def sample_async_weighted(self, state: int, pr: dict[str, float], r: float,
                              changes: Optional[list[int]] = None
                              ) -> tuple[Model, str, int]:
        """Pick one changeable variable with probability proportional to ``p``.

        The absolute scale of the weights cancels.  Variables with zero
        weight are never selected, and a state whose changeable variables all
        have zero weight has no weighted-asynchronous transition.
        """
        if changes is None:
            changes = self.potential_changes(state)
        if not changes:
            raise ValueError("weighted async sampling is undefined at a steady state")
        weights = []
        for v in changes:
            weight = pr[self.names[v]]
            if not math.isfinite(weight) or weight < 0.0:
                raise ValueError(f"invalid firing weight for {self.names[v]}: {weight}")
            weights.append(weight)
        total = math.fsum(weights)
        if total <= 0.0:
            raise ValueError(
                "weighted async sampling needs a positive firing weight")

        target = min(max(r, 0.0), 1.0) * total
        cumulative = 0.0
        selected = None
        for bit, weight in enumerate(weights):
            if weight == 0.0:
                continue
            selected = bit
            cumulative += weight
            if target < cumulative:
                break

        assert selected is not None
        fired = [False] * len(weights)
        fired[selected] = True
        return self._assemble(state, changes, fired)

    def _assemble(self, state: int, changes: list[int],
                  fired: list[bool]) -> tuple[Model, str, int]:
        """Turn a firing decision per changeable variable into a leaf."""
        nxt = state
        model: list[tuple[str, bool]] = []
        for bit, v in enumerate(changes):
            if fired[bit]:
                nxt ^= 1 << v
            model.append((self.names[v], fired[bit]))
        m_str = "{" + ";".join(("" if f else "!") + name for name, f in model) + "}"
        return (tuple(model), m_str, nxt)


def parse_bnet(text: str) -> BNet:
    """Parse the ``.bnet`` format (a ``targets, factors`` header plus rules)."""
    if not text.endswith("\n"):
        text += "\n"
    try:
        rules = _TO_AST.transform(_PARSER.parse(text, start="start"))
    except UnexpectedInput as e:
        raise ValueError(f"invalid .bnet input: {e}") from e

    order: list[str] = []
    funcs: dict[str, Optional[Expr]] = {}
    for name, expr in rules:
        if name not in funcs:
            order.append(name)
        funcs[name] = expr

    index = {name: i for i, name in enumerate(order)}
    update: list[Expr] = []
    referenced: set[str] = set()
    for name in order:
        expr = funcs[name]
        if expr is not None:
            referenced |= vars_of(expr)
            update.append(expr)
        else:
            # A target without an update function is (at least) a constant node.
            update.append(Var(name))

    # Variables that occur on the right-hand side but are never defined are
    # inputs: with no update rule they hold their value (self-loop).
    for name in sorted(referenced - set(order)):
        order.append(name)
        index[name] = len(order) - 1
        update.append(Var(name))

    return BNet(order, index, update)


def parse_bnet_file(path: str | Path) -> BNet:
    return parse_bnet(Path(path).read_text())
